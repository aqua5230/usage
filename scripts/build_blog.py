def _format_sitemap_url(loc: str, lastmod: str, hreflangs: dict[str, str]) -> str:
    links = [
        f'    <xhtml:link rel="alternate" hreflang="{lang}" '
        f'href="{html.escape(hreflangs[lang], quote=True)}"/>'
        for lang in LANGS
        if lang in hreflangs
    ]
    if "en" in hreflangs:
        en_href = html.escape(hreflangs["en"], quote=True)
        links.append(f'    <xhtml:link rel="alternate" hreflang="x-default" href="{en_href}"/>')
    return (
        "  <url>\n"
        f"    <loc>{html.escape(loc, quote=True)}</loc>\n"
        f"    <lastmod>{lastmod}</lastmod>\n" + "\n".join(links) + "\n  </url>"
    )


def render_sitemap(
    existing_sitemap: str,
    articles: dict[str, dict[str, Article]],
    posts_by_lang: dict[str, list[Article]],
) -> str:
    if SITEMAP_START not in existing_sitemap or SITEMAP_END not in existing_sitemap:
        raise ValueError(f"sitemap.xml must contain {SITEMAP_START} and {SITEMAP_END}")
    before, rest = existing_sitemap.split(SITEMAP_START, 1)
    _, after = rest.split(SITEMAP_END, 1)

    list_langs = [lang for lang in LANGS if lang in posts_by_lang]
    entries: list[str] = []
    if list_langs:
        list_hreflangs = {lang: list_url(lang) for lang in list_langs}
        for lang in list_langs:
            lastmod = max(post.lastmod for post in posts_by_lang[lang])
            entries.append(_format_sitemap_url(list_url(lang), lastmod, list_hreflangs))

        sorted_slugs = sorted(
            articles.keys(),
            key=lambda s: (max(a.date for a in articles[s].values()), s),
            reverse=True,
        )
        for slug in sorted_slugs:
            per_lang = articles[slug]
            art_hreflangs = {lang: article_url(slug, lang) for lang in LANGS if lang in per_lang}
            for lang in LANGS:
                if lang not in per_lang:
                    continue
                art = per_lang[lang]
                entries.append(
                    _format_sitemap_url(article_url(slug, lang), art.lastmod, art_hreflangs)
                )

    middle = "\n" + "\n".join(entries) + "\n" if entries else "\n"
    return f"{before}{SITEMAP_START}{middle}{SITEMAP_END}{after}"


def render_homepage_latest_posts(
    existing_index: str,
    posts_by_lang: dict[str, list[Article]],
) -> str:
    """Replace the latest-posts marker block in docs/index.html with up to 3 posts per lang."""
    if LATEST_POSTS_START not in existing_index or LATEST_POSTS_END not in existing_index:
        raise ValueError(
            f"docs/index.html must contain {LATEST_POSTS_START} and {LATEST_POSTS_END}"
        )
    before, rest = existing_index.split(LATEST_POSTS_START, 1)
    if LATEST_POSTS_END not in rest:
        raise ValueError(
            f"docs/index.html must contain {LATEST_POSTS_START} before {LATEST_POSTS_END}"
        )
    _, after = rest.split(LATEST_POSTS_END, 1)

    groups: list[str] = []
    for lang in LANGS:
        posts = posts_by_lang.get(lang)
        if not posts:
            continue
        latest = sorted(posts, key=lambda a: (a.date, a.slug), reverse=True)[:LATEST_POSTS_LIMIT]
        cards: list[str] = []
        for post in latest:
            post_href = f"blog/{post.slug}/" if lang == "en" else f"{lang}/blog/{post.slug}/"
            cards.append(
                f'      <a class="latest-post" href="{html.escape(post_href, quote=True)}">\n'
                f'        <time datetime="{post.date}">{post.date}</time>\n'
                f"        <h3>{html.escape(post.title)}</h3>\n"
                f"        <p>{html.escape(post.description)}</p>\n"
                "      </a>"
            )
        hidden_attr = "" if lang == "en" else " hidden"
        groups.append(
            f'    <div class="latest-posts" data-posts-lang="{lang}"{hidden_attr}>\n'
            + "\n".join(cards)
            + "\n    </div>"
        )

    middle = "\n" + "\n".join(groups) + "\n" if groups else "\n"
    return f"{before}{LATEST_POSTS_START}{middle}{LATEST_POSTS_END}{after}"


def build_outputs(
    source_dir: Path, docs_dir: Path, sitemap_text: str, index_text: str
) -> tuple[dict[Path, str | bytes], str, str]:
    articles = load_articles(source_dir)
    md = MarkdownIt("commonmark", {"html": False}).enable("table")

    outputs: dict[Path, str | bytes] = {}
    posts_by_lang: dict[str, list[Article]] = {}
    for per_lang in articles.values():
        for lang, article in per_lang.items():
            posts_by_lang.setdefault(lang, []).append(article)

    for posts in posts_by_lang.values():
        posts.sort(key=lambda a: (a.date, a.slug), reverse=True)

    list_langs = [lang for lang in LANGS if lang in posts_by_lang]
    latest_by_lang = {lang: posts[:LATEST_POSTS_LIMIT] for lang, posts in posts_by_lang.items()}
    if list_langs:
        for filename in TOOL_LOGOS.values():
            outputs[docs_dir / "blog" / "icons" / filename] = (
                REPO_ROOT / "assets" / filename
            ).read_bytes()
    for lang in list_langs:
        outputs[list_output_path(docs_dir, lang)] = render_list_page(
            lang, posts_by_lang[lang], list_langs, md
        )

    for slug, per_lang in articles.items():
        slug_images = load_slug_images(source_dir / slug)
        for filename, img_path in slug_images.items():
            outputs[image_output_path(docs_dir, slug, filename)] = img_path.read_bytes()
        for lang, article in per_lang.items():
            outputs[article_output_path(docs_dir, slug, lang)] = render_article(
                article, per_lang, articles, md, slug_images, latest_posts=latest_by_lang[lang]
            )

    new_sitemap = render_sitemap(sitemap_text, articles, posts_by_lang)
    new_index = render_homepage_latest_posts(index_text, posts_by_lang)
    return outputs, new_sitemap, new_index


def find_existing_blog_files(docs_dir: Path) -> set[Path]:
    if not docs_dir.is_dir():
        return set()
    found: set[Path] = set()
    for path in docs_dir.rglob("*"):
        if not path.is_file():
            continue
        rel_parts = path.relative_to(docs_dir).parts
        if "blog" in rel_parts:
            found.add(path)
    return found


def run_build(*, check: bool) -> int:
    sitemap_file = _sitemap_path()
    if not sitemap_file.is_file():
        print(f"Missing sitemap: {sitemap_file}", file=sys.stderr)
        return 1
    index_file = _index_path()
    if not index_file.is_file():
        print(f"Missing index: {index_file}", file=sys.stderr)
        return 1
    sitemap_text = sitemap_file.read_text(encoding="utf-8")
    index_text = index_file.read_text(encoding="utf-8")
    outputs, expected_sitemap, expected_index = build_outputs(
        SOURCE_DIR, DOCS_DIR, sitemap_text, index_text
    )
    existing_files = find_existing_blog_files(DOCS_DIR)
    orphans = sorted(existing_files - set(outputs.keys()))

    if check:
        problems: list[Path] = []
        for path, content in sorted(outputs.items()):
            if not path.is_file():
                problems.append(path)
            elif isinstance(content, bytes):
                if path.read_bytes() != content:
                    problems.append(path)
            elif path.read_text(encoding="utf-8") != content:
                problems.append(path)
        problems.extend(orphans)
        if sitemap_text != expected_sitemap:
            problems.append(sitemap_file)
        if index_text != expected_index:
            problems.append(index_file)
        if problems:
            for item in problems:
                print(item)
            return 1
        return 0

    for orphan in orphans:
        orphan.unlink()
        parent = orphan.parent
        while parent != DOCS_DIR and parent.is_dir() and not any(parent.iterdir()):
            parent.rmdir()
            parent = parent.parent

    for path, content in sorted(outputs.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            path.write_bytes(content)
        else:
            path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")

    if sitemap_text != expected_sitemap:
        sitemap_file.write_text(expected_sitemap, encoding="utf-8")
        print(f"updated {sitemap_file}")
    if index_text != expected_index:
        index_file.write_text(expected_index, encoding="utf-8")
        print(f"updated {index_file}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args(argv)
    return run_build(check=bool(args.check))


if __name__ == "__main__":
    sys.exit(main())
