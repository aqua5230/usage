def load_slug_images(slug_dir: Path) -> dict[str, Path]:
    images: dict[str, Path] = {}
    if not slug_dir.is_dir():
        return images
    for entry in sorted(slug_dir.iterdir()):
        if not entry.is_file() or entry.name.startswith("."):
            continue
        if entry.suffix.lower() in IMAGE_EXTENSIONS | EMBED_EXTENSIONS:
            images[entry.name] = entry
    return images


def _validate_date(value: str, field: str, path: Path) -> str:
    if not DATE_RE.match(value):
        raise ValueError(f"{path}: {field} must be YYYY-MM-DD, got {value!r}")
    try:
        date.fromisoformat(value)
    except ValueError as exc:
        raise ValueError(f"{path}: invalid {field} {value!r}") from exc
    return value


def parse_frontmatter(raw: str, path: Path) -> tuple[dict[str, str], str]:
    normalized = raw.replace("\r\n", "\n").replace("\r", "\n")
    lines = normalized.split("\n")
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path}: frontmatter must start with '---'")
    end_idx: int | None = None
    for idx in range(1, len(lines)):
        if lines[idx].strip() == "---":
            end_idx = idx
            break
    if end_idx is None:
        raise ValueError(f"{path}: missing closing '---' in frontmatter")

    meta: dict[str, str] = {}
    for line in lines[1:end_idx]:
        if not line.strip():
            continue
        if ":" not in line:
            raise ValueError(f"{path}: invalid frontmatter line {line!r}")
        key, value = line.split(":", 1)
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ('"', "'"):
            value = value[1:-1]
        meta[key] = value

    body = "\n".join(lines[end_idx + 1 :]).lstrip("\n")
    return meta, body


def load_articles(source_dir: Path) -> dict[str, dict[str, Article]]:
    articles: dict[str, dict[str, Article]] = {}
    if not source_dir.is_dir():
        return articles

    for slug_dir in sorted(source_dir.iterdir()):
        if not slug_dir.is_dir() or slug_dir.name.startswith("."):
            continue
        slug = slug_dir.name
        slug_images = load_slug_images(slug_dir)
        per_lang: dict[str, Article] = {}
        for lang in LANGS:
            md_path = slug_dir / f"{lang}.md"
            if not md_path.is_file():
                continue
            meta, body = parse_frontmatter(md_path.read_text(encoding="utf-8"), md_path)
            title = meta.get("title", "").strip()
            description = meta.get("description", "").strip()
            raw_date = meta.get("date", "").strip()
            if not title or not description or not raw_date:
                raise ValueError(
                    f"{md_path}: frontmatter requires non-empty title, description, and date"
                )
            pub_date = _validate_date(raw_date, "date", md_path)
            raw_updated = meta.get("updated", "").strip()
            updated = _validate_date(raw_updated, "updated", md_path) if raw_updated else None
            related = tuple(
                part.strip() for part in meta.get("related", "").split(",") if part.strip()
            )
            raw_image = meta.get("image", "").strip()
            image = raw_image or None
            if image is not None and image not in slug_images:
                raise ValueError(f"{md_path}: unknown image {image!r}")
            per_lang[lang] = Article(
                slug=slug,
                lang=lang,
                title=title,
                description=description,
                date=pub_date,
                updated=updated,
                related=related,
                body_markdown=body,
                image=image,
                tool=meta.get("tool", "").strip() or None,
            )
        if per_lang:
            articles[slug] = per_lang
    return articles


