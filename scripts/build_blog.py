            if target is None:
                raise ValueError(
                    f"site/blog/{article.slug}/{lang}.md: "
                    f"related slug {rel_slug!r} has neither {lang} nor en"
                )
            rel_href = (
                f"{root_rel}blog/{rel_slug}/"
                if target.lang == "en"
                else f"{root_rel}{target.lang}/blog/{rel_slug}/"
            )
            items.append(
                f'      <li><a href="{html.escape(rel_href, quote=True)}">'
                f"{html.escape(target.title)}</a></li>"
            )
