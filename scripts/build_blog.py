def slugify_heading(text: str) -> str:
    cleaned = re.sub(r"[^\w\s-]", "", text.lower())
    slug = re.sub(r"[-\s]+", "-", cleaned).strip("-")
    return slug or "section"


def add_heading_ids_and_extract_toc(body_html: str) -> tuple[str, list[tuple[str, str]]]:
    used_ids: set[str] = set()
    headings: list[tuple[str, str]] = []

    def _replace(match: re.Match[str]) -> str:
        inner_html = match.group(1)
        plain_text = html.unescape(TAG_RE.sub("", inner_html)).strip()
        base_slug = slugify_heading(plain_text)
        heading_id = base_slug
        suffix = 2
        while heading_id in used_ids:
            heading_id = f"{base_slug}-{suffix}"
            suffix += 1
        used_ids.add(heading_id)
        headings.append((heading_id, plain_text))
        return f'<h2 id="{html.escape(heading_id, quote=True)}">{inner_html}</h2>'

    return H2_RE.sub(_replace, body_html), headings


def _render_toc_list(headings: list[tuple[str, str]]) -> str:
    items = "\n".join(
        f'          <li><a href="#{html.escape(hid, quote=True)}">{html.escape(label)}</a></li>'
        for hid, label in headings
    )
    return f'        <ol class="toc-list">\n{items}\n        </ol>'


