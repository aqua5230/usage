"""Generate GitHub Pages redirects for the retired website."""

from __future__ import annotations

import argparse
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"
SITE = "https://getusage.app"

# Keep the retired routes fixed so --check also catches a deleted redirect.
INDEX_ROUTES = (
    "/",
    "/ja/",
    "/ko/",
    "/zh-CN/",
    "/zh-TW/",
    "/blog/",
    "/blog/claude-code-idle-compaction/",
    "/blog/claude-code-weekly-limit-reset/",
    "/blog/codex-weekly-limit-early-reset/",
    "/blog/how-to-check-antigravity-quota/",
    "/blog/what-is-cli/",
    "/zh-TW/blog/",
    "/zh-TW/blog/claude-code-codex-not-working/",
    "/zh-TW/blog/claude-code-idle-compaction/",
    "/zh-TW/blog/claude-code-weekly-limit-reset/",
    "/zh-TW/blog/codex-weekly-limit-early-reset/",
    "/zh-TW/blog/how-to-check-antigravity-quota/",
    "/zh-TW/blog/what-is-cli/",
)


def render_redirect(url: str, destination: str) -> str:
    return f"""<!doctype html>
<!-- Generated by scripts/build_redirects.py. Do not edit. -->
<html lang="en">
<meta charset="utf-8">
<title>usage has moved</title>
<meta http-equiv="refresh" content="0; url={url}">
<link rel="canonical" href="{url}">
<meta name="robots" content="noindex">
<script>
  location.replace({destination} + location.search + location.hash);
</script>
<a href="{url}">usage has moved to getusage.app</a>
</html>
"""


def build_redirects(docs: Path, *, check: bool) -> int:
    pages = {
        Path(route.lstrip("/")) / "index.html": render_redirect(SITE + route, f'"{SITE}{route}"')
        for route in INDEX_ROUTES
    }
    missing_path = r'location.pathname.replace(/^\/usage(?=\/|$)/, "") || "/"'
    pages[Path("404.html")] = render_redirect(f"{SITE}/", f'"{SITE}" + ({missing_path})')

    outdated = False
    for relative, page in pages.items():
        path = docs / relative
        if check:
            if not path.is_file() or path.read_bytes() != page.encode("utf-8"):
                print(f"Out of date: {path}")
                outdated = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(page, encoding="utf-8", newline="\n")
    return int(outdated)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report differences without writing")
    args = parser.parse_args()
    return build_redirects(DOCS, check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
